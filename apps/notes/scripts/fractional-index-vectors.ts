/**
 * Prints cases of `fractional-indexing` for the iPad's port of it to match key for key:
 * `bun apps/notes/scripts/fractional-index-vectors.ts > apps/notes/ios/NotesKit/Tests/NotesKitTests/FractionalIndexVectors.swift`
 */
import { generateKeyBetween } from "fractional-indexing";

type Case = { readonly before: string | null; readonly after: string | null; readonly key: string };

const between = (before: string | null, after: string | null): Case => ({
  before,
  after,
  key: generateKeyBetween(before, after),
});

/** A fixed linear congruential sequence in [0, 1), so the cases are the same on every run. */
const randoms = (seed: number, count: number): number[] =>
  Array.from({ length: count }).reduce<{ seed: number; values: number[] }>(
    (state) => {
      const next = (state.seed * 1103515245 + 12345) % 2147483648;
      return { seed: next, values: [...state.values, next / 2147483648] };
    },
    { seed, values: [] },
  ).values;

/** Inserts at random places among the keys made so far. */
const scattered = randoms(7, 300).reduce<{ keys: string[]; cases: Case[] }>(
  (state, random) => {
    const sorted = state.keys.toSorted();
    const at = Math.floor(random * (sorted.length + 1));
    const made = between(sorted[at - 1] ?? null, sorted[at] ?? null);
    return { keys: [...state.keys, made.key], cases: [...state.cases, made] };
  },
  { keys: [], cases: [] },
).cases;

/** Appends or prepends 4,000 times, crossing integer heads, keeping every 40th case. */
const runOf = (step: (last: string | null) => Case): Case[] =>
  Array.from({ length: 4000 })
    .reduce<{ last: string | null; cases: Case[] }>(
      (state) => {
        const made = step(state.last);
        return { last: made.key, cases: [...state.cases, made] };
      },
      { last: null, cases: [] },
    )
    .cases.filter((_, i) => i % 40 === 0);

/** Halves the gap between two keys 80 times, alternating sides, for long fractions. */
const narrowing = Array.from({ length: 80 }).reduce<{ lo: string; hi: string; cases: Case[] }>(
  (state, _, i) => {
    const made = between(state.lo, state.hi);
    const cases = [...state.cases, made];
    return i % 2 === 0 ? { lo: state.lo, hi: made.key, cases } : { lo: made.key, hi: state.hi, cases };
  },
  { lo: "a0", hi: "a1", cases: [] },
).cases;

const cases = [
  ...scattered,
  ...runOf((last) => between(last, null)),
  ...runOf((first) => between(null, first)),
  ...narrowing,
];

const swift = (value: string | null): string => (value === null ? "nil" : JSON.stringify(value));

console.log(`// Generated by apps/notes/scripts/fractional-index-vectors.ts from the server's fractional-indexing.
let fractionalIndexVectors: [(String?, String?, String)] = [
${cases.map((c) => `    (${swift(c.before)}, ${swift(c.after)}, ${swift(c.key)}),`).join("\n")}
]`);
